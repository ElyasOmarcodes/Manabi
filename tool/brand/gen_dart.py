"""Writes app/lib/ui/widgets/brand_paths.dart from app/assets/brand/almanabea.svg."""
import re, sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
svg = (root / "app/assets/brand/almanabea.svg").read_text()
vb = [float(v) for v in re.search(r'viewBox="([^"]+)"', svg).group(1).split()]
ink = re.search(r'id="ink"[^>]* d="([^"]+)"', svg).group(1)
latin = re.search(r'id="latin"[^>]* d="([^"]+)"', svg).group(1)
mark_svg = (root / "app/assets/brand/almanabea_mark.svg").read_text()
mvb = [float(v) for v in re.search(r'viewBox="([^"]+)"', mark_svg).group(1).split()]
out = f"""// GENERATED by tool/brand/gen_dart.py from assets/brand/almanabea.svg. Do not edit.
import 'dart:ui';

const brandViewBox = Rect.fromLTWH({vb[0]}, {vb[1]}, {vb[2]}, {vb[3]});
const brandMarkViewBox = Rect.fromLTWH({mvb[0]}, {mvb[1]}, {mvb[2]}, {mvb[3]});
const brandInkPath = '{ink}';
const brandLatinPath = '{latin}';
"""
target = root / "app/lib/ui/widgets/brand_paths.dart"
if "--check" in sys.argv:
    sys.exit(0 if target.read_text() == out else "brand_paths.dart is out of date")
target.write_text(out)
